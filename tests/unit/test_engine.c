/* Generated by Python (zlib.crc32, independent of the C code). Key byte i =
 * (i*7 + 3 + (i>>8)*13) & 0xFF, key length 1024, Key ID 0x0000BEEF,
 * plaintext "Einszeit KAT 01". */
static const uint8_t KAT_ALICE_1[35] = {
	0x5a, 0x45, 0x01, 0x00, 0xef, 0xbe, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x0f, 0x00, 0x00, 0x00, 0x46, 0x63, 0x7f, 0x6b, 0x65, 0x43, 0x44, 0x40,
	0x1b, 0x09, 0x08, 0x04, 0x77, 0x6e, 0x54, 0x56, 0x2c, 0xad, 0x83,
};
static const uint8_t KAT_ALICE_2[35] = {
	0x5a, 0x45, 0x01, 0x00, 0xef, 0xbe, 0x00, 0x00, 0x0f, 0x00, 0x00, 0x00,
	0x0f, 0x00, 0x00, 0x00, 0x29, 0x1a, 0x14, 0xf2, 0xf2, 0xea, 0xff, 0xe9,
	0x84, 0xe0, 0xf3, 0xed, 0xe0, 0xf7, 0xff, 0xd9, 0x41, 0xbf, 0xc0,
};
static const uint8_t KAT_BOB_1[35] = {
	0x5a, 0x45, 0x01, 0x00, 0xef, 0xbe, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00,
	0x0f, 0x00, 0x00, 0x00, 0x58, 0x4d, 0x45, 0x41, 0x43, 0x25, 0x2e, 0x3a,
	0x75, 0x17, 0x22, 0x3e, 0x51, 0x48, 0x4e, 0xda, 0x7b, 0xf0, 0x7f,
};

#define KAT_ID 0x0000BEEFu
static const char KAT_PT[] = "Einszeit KAT 01";
#define KAT_LEN 15u

static void put_kat_key(ezdev_t *d)
{
	uint8_t k[1024];
	for (int i = 0; i < 1024; i++) k[i] = (uint8_t)(i * 7 + 3 + (i >> 8) * 13);
	char name[EZ_FNAME_MAX];
	ez_key_name(KAT_ID, "KEY", name);
	sim_ks_put(&d->ks, 1, name, k, sizeof k);
	put_sum(&d->ks, 1, KAT_ID, k, sizeof k, 0x4B41);
}

static uint8_t out[1 << 20], out2[1 << 20], pt[1 << 20];

/* SEC-TEST-ENC-001, SEC-TEST-ENC-002, SEC-TX-002 */
static void t_kat(void)
{
	for (int mode = 0; mode < 2; mode++) {
		ezdev_t *a = dev_new(1), *b = dev_new(2);
		put_kat_key(a); put_kat_key(b);
		int sa = dev_session(a, KAT_ID, 1, EZ_ROLE_ALICE, "bob");
		int sb = dev_session(b, KAT_ID, 1, EZ_ROLE_BOB, "alice");
		uint32_t n;
		for (int k = 0; k < 2; k++) {
			const uint8_t *want = k == 0 ? KAT_ALICE_1 : KAT_ALICE_2;
			ez_status_t st = mode == 0
				? dev_encrypt(a, sa, (const uint8_t *)KAT_PT, KAT_LEN, out, &n)
				: dev_encrypt_stream(a, sa, (const uint8_t *)KAT_PT, KAT_LEN, 4, out, &n);
			EZ_CHECK_EQ(st, EZ_OK);
			EZ_CHECK_EQ(n, sizeof KAT_ALICE_1);          /* header + N + CRC only */
			EZ_CHECK_MSG(memcmp(out, want, n) == 0, "KAT mismatch (alice)");
			DEV_KBUF_CLEAR(a);
		}
		/* SEC-TEST-ENC-002: same plaintext, different offsets */
		EZ_CHECK(memcmp(KAT_ALICE_1 + 16, KAT_ALICE_2 + 16, KAT_LEN) != 0);
		EZ_CHECK_EQ(mode == 0 ? dev_encrypt(b, sb, (const uint8_t *)KAT_PT, KAT_LEN, out, &n)
		                      : dev_encrypt_stream(b, sb, (const uint8_t *)KAT_PT, KAT_LEN, 1, out, &n),
		            EZ_OK);
		EZ_CHECK_MSG(memcmp(out, KAT_BOB_1, n) == 0, "KAT mismatch (bob)");
		/* And decryption of the published vectors. */
		EZ_CHECK_EQ(dev_decrypt(b, sb, KAT_ALICE_1, sizeof KAT_ALICE_1, pt, &n), EZ_OK);
		EZ_CHECK(n == KAT_LEN && memcmp(pt, KAT_PT, n) == 0);
		EZ_CHECK_EQ(dev_decrypt_stream(b, sb, KAT_ALICE_2, sizeof KAT_ALICE_2, 3, pt, &n), EZ_OK);
		EZ_CHECK(n == KAT_LEN && memcmp(pt, KAT_PT, n) == 0);
		EZ_CHECK_EQ(dev_decrypt(a, sa, KAT_BOB_1, sizeof KAT_BOB_1, pt, &n), EZ_OK);
		EZ_CHECK(n == KAT_LEN && memcmp(pt, KAT_PT, n) == 0);
		DEV_KBUF_CLEAR(a); DEV_KBUF_CLEAR(b);
		dev_free(a); dev_free(b);
	}
}

/* Two devices exchanging many messages both ways, buffered and streamed,
 * including sizes that cross key-block boundaries. */
static void t_interop(void)
{
	ezdev_t *a = dev_new(3), *b = dev_new(4);
	dev_put_key(a, 1, 0x1234, 1u << 22, 77);            /* 4 MiB */
	dev_copy_key(a, b, 1, 0x1234);
	int sa = dev_session(a, 0x1234, 1, EZ_ROLE_ALICE, "b");
	int sb = dev_session(b, 0x1234, 1, EZ_ROLE_BOB, "a");
	static const uint32_t sizes[] = { 1, 2, 511, 512, 513, 1000, 4096, 65536, 70000, 300000 };
	for (unsigned i = 0; i < sizeof sizes / sizeof sizes[0]; i++) {
		uint32_t len = sizes[i], n, m;
		sim_fill(pt, len, 1000 + i);
		for (int dir = 0; dir < 2; dir++) {
			ezdev_t *tx = dir ? b : a, *rx = dir ? a : b;
			int stx = dir ? sb : sa, srx = dir ? sa : sb;
			bool buffered = len <= EZ_BUFFERED_MAX && (i & 1);
			ez_status_t st = buffered ? dev_encrypt(tx, stx, pt, len, out, &n)
			                          : dev_encrypt_stream(tx, stx, pt, len, 58, out, &n);
			EZ_CHECK_EQ(st, EZ_OK);
			EZ_CHECK_EQ(n, len + EZ_MSG_OVERHEAD);
			st = (len <= EZ_BUFFERED_MAX && !(i & 2)) ? dev_decrypt(rx, srx, out, n, out2, &m)
			                                          : dev_decrypt_stream(rx, -1, out, n, 61, out2, &m);
			EZ_CHECK_EQ(st, EZ_OK);
			EZ_CHECK_EQ(m, len);
			EZ_CHECK(memcmp(out2, pt, len) == 0);
			DEV_KBUF_CLEAR(tx); DEV_KBUF_CLEAR(rx);
		}
	}
	dev_free(a); dev_free(b);
}

/* SEC-TEST-ENC-003: no API takes an offset for encryption; each
 * encryption starts where the last ended, and the metadata layer refuses
 * to move the offset back. */
static void t_no_reencrypt_at_same_offset(void)
{
	ezdev_t *a = dev_new(5);
	dev_put_key(a, 1, 0x77, 4096, 1);
	int s = dev_session(a, 0x77, 1, EZ_ROLE_ALICE, "x");
	uint32_t n, off[3];
	for (int i = 0; i < 3; i++) {
		EZ_CHECK_EQ(dev_encrypt(a, s, (const uint8_t *)"same", 4, out, &n), EZ_OK);
		off[i] = ez_get_le32(out + 8);
	}
	EZ_CHECK(off[0] == 0 && off[1] == 4 && off[2] == 8);
	EZ_CHECK_EQ(ez_meta_commit_tx(&a->c.meta, s, 4), EZ_ERR_ROLLBACK);
	dev_reboot(a);
	EZ_CHECK_EQ(dev_encrypt(a, s, (const uint8_t *)"same", 4, out, &n), EZ_OK);
	EZ_CHECK_EQ(ez_get_le32(out + 8), 12);
	dev_free(a);
}

static bool reads_only(ezdev_t *d, uint32_t key_id, uint32_t lo, uint32_t hi)
{
	char name[EZ_FNAME_MAX];
	ez_key_name(key_id, "KEY", name);
	char sum[EZ_FNAME_MAX];
	ez_key_name(key_id, "SUM", sum);
	for (uint32_t i = 0; i < d->ks.nlog; i++) {
		const sim_read_t *r = &d->ks.log[i];
		if (strcmp(r->name, sum) == 0) continue;     /* integrity tags */
		if (strcmp(r->name, name) != 0) return false;
		if (r->off < lo || (uint64_t)r->off + r->len > hi) return false;
	}
	return true;
}

/* SEC-TEST-ISO-002 */
static void t_session_isolation(void)
{
	ezdev_t *d = dev_new(6);
	dev_put_key(d, 1, 0xA, 8192, 1);
	dev_put_key(d, 1, 0xB, 8192, 2);
	int a = dev_session(d, 0xA, 1, EZ_ROLE_ALICE, "a");
	int b = dev_session(d, 0xB, 1, EZ_ROLE_BOB, "b");
	uint32_t n;
	for (int i = 0; i < 20; i++) {
		sim_ks_log_reset(&d->ks, true);
		EZ_CHECK_EQ(dev_encrypt(d, a, pt, 100, out, &n), EZ_OK);
		EZ_CHECK_MSG(reads_only(d, 0xA, 0, 4096), "A read outside A's TX range");
		sim_ks_log_reset(&d->ks, true);
		EZ_CHECK_EQ(dev_encrypt_stream(d, b, pt, 100, 7, out, &n), EZ_OK);
		EZ_CHECK_MSG(reads_only(d, 0xB, 4096, 8192), "B read outside B's TX range");
	}
	sim_ks_log_reset(&d->ks, false);
	dev_free(d);
}

/* SEC-TEST-ISO-003 */
static void t_tx_rx_ranges(void)
{
	ezdev_t *a = dev_new(7), *b = dev_new(8);
	dev_put_key(a, 1, 0x99, 8192, 3);
	dev_copy_key(a, b, 1, 0x99);
	int sa = dev_session(a, 0x99, 1, EZ_ROLE_ALICE, "b");
	int sb = dev_session(b, 0x99, 1, EZ_ROLE_BOB, "a");
	uint32_t n, m;
	EZ_CHECK_EQ(dev_encrypt(b, sb, pt, 300, out, &n), EZ_OK);
	uint32_t tx_before = a->c.meta.s[sa].tx_off;
	sim_ks_log_reset(&a->ks, true);
	EZ_CHECK_EQ(dev_decrypt(a, sa, out, n, out2, &m), EZ_OK);
	EZ_CHECK_MSG(reads_only(a, 0x99, 4096, 8192), "decryption read outside the RX range");
	EZ_CHECK_MSG(a->c.meta.s[sa].tx_off == tx_before, "decryption moved the TX offset");
	EZ_CHECK_EQ(a->c.meta.s[sa].rx_off, 4096 + 300);
	dev_reboot(a);
	EZ_CHECK_EQ(a->c.meta.s[sa].tx_off, tx_before);

	/* A message claiming an offset in alice's own TX range (her own
	 * message, or a forgery) is outside her RX range: rejected with no
	 * key read at all. */
	EZ_CHECK_EQ(dev_encrypt(a, sa, pt, 50, out, &n), EZ_OK);
	sim_ks_log_reset(&a->ks, true);
	EZ_CHECK_EQ(dev_decrypt(a, sa, out, n, out2, &m), EZ_ERR_RANGE);
	EZ_CHECK_EQ(a->ks.nlog, 0);
	/* One that would run past the end of the key. */
	ez_msg_hdr_t h = { 0x99, 8000, 500 };
	ez_msg_hdr_encode(&h, out);
	memset(out + 16, 0, 500);
	ez_put_le32(out + 516, ez_crc32(out, 516));
	sim_ks_log_reset(&a->ks, true);
	EZ_CHECK_EQ(dev_decrypt(a, sa, out, 520, out2, &m), EZ_ERR_RANGE);
	EZ_CHECK_EQ(dev_decrypt_stream(a, sa, out, 520, 64, out2, &m), EZ_ERR_RANGE);
	EZ_CHECK_EQ(a->ks.nlog, 0);
	/* Encryption beyond the TX range is refused before reading. */
	sim_ks_log_reset(&a->ks, true);
	EZ_CHECK_EQ(dev_encrypt_stream(a, sa, pt, 4096, 64, out, &n), EZ_ERR_CAPACITY);
	EZ_CHECK_EQ(a->ks.nlog, 0);
	dev_free(a); dev_free(b);
}

/* SEC-TEST-REPLAY-001 */
static void t_replay(void)
{
	ezdev_t *a = dev_new(9), *b = dev_new(10);
	dev_put_key(a, 1, 0x55, 8192, 4);
	dev_copy_key(a, b, 1, 0x55);
	int sa = dev_session(a, 0x55, 1, EZ_ROLE_ALICE, "b");
	int sb = dev_session(b, 0x55, 1, EZ_ROLE_BOB, "a");
	static uint8_t m1[200], m2[200];
	uint32_t n1, n2, m;
	EZ_CHECK_EQ(dev_encrypt(a, sa, pt, 100, m1, &n1), EZ_OK);
	EZ_CHECK_EQ(dev_encrypt(a, sa, pt, 100, m2, &n2), EZ_OK);
	EZ_CHECK_EQ(dev_decrypt(b, sb, m1, n1, out, &m), EZ_OK);
	for (int mode = 0; mode < 2; mode++) {
		sim_ks_log_reset(&b->ks, true);
		EZ_CHECK_EQ(mode ? dev_decrypt_stream(b, sb, m1, n1, 16, out, &m)
		                 : dev_decrypt(b, sb, m1, n1, out, &m), EZ_ERR_REPLAY);
		EZ_CHECK_MSG(b->ks.nlog == 0, "replay rejected only after reading key bytes");
	}
	/* After a reboot too. */
	dev_reboot(b);
	EZ_CHECK_EQ(dev_decrypt(b, sb, m1, n1, out, &m), EZ_ERR_REPLAY);
	/* Out of order: m2 first, then m1 -- m1 is below the RX offset. */
	ezdev_t *c = dev_new(11);
	dev_copy_key(a, c, 1, 0x55);
	int sc = dev_session(c, 0x55, 1, EZ_ROLE_BOB, "a");
	EZ_CHECK_EQ(dev_decrypt(c, sc, m2, n2, out, &m), EZ_OK);
	sim_ks_log_reset(&c->ks, true);
	EZ_CHECK_EQ(dev_decrypt(c, sc, m1, n1, out, &m), EZ_ERR_REPLAY);
	EZ_CHECK_EQ(c->ks.nlog, 0);
	dev_free(a); dev_free(b); dev_free(c);
}

/* SEC-DEC-002, IMPL-MSG-001 */
static void t_key_id(void)
{
	ezdev_t *a = dev_new(12), *b = dev_new(13);
	dev_put_key(a, 1, 0x11, 8192, 5);
	dev_put_key(a, 1, 0x22, 8192, 6);
	dev_copy_key(a, b, 1, 0x11);
	dev_copy_key(a, b, 1, 0x22);
	int a1 = dev_session(a, 0x11, 1, EZ_ROLE_ALICE, "one");
	int b1 = dev_session(b, 0x11, 1, EZ_ROLE_BOB, "one");
	int b2 = dev_session(b, 0x22, 1, EZ_ROLE_BOB, "two");
	uint32_t n, m;
	EZ_CHECK_EQ(dev_encrypt(a, a1, pt, 64, out, &n), EZ_OK);
	sim_ks_log_reset(&b->ks, true);
	EZ_CHECK_EQ(dev_decrypt(b, b2, out, n, out2, &m), EZ_ERR_KEY_ID);   /* wrong session named */
	EZ_CHECK_EQ(b->ks.nlog, 0);
	EZ_CHECK_EQ(dev_decrypt(b, -1, out, n, out2, &m), EZ_OK);           /* selected by Key ID */
	EZ_CHECK_EQ(b->c.meta.s[b1].rx_off, 64);
	EZ_CHECK_EQ(b->c.meta.s[b2].rx_off, 0);
	ez_put_le32(out + 4, 0x33);                                        /* unknown Key ID */
	ez_put_le32(out + n - 4, ez_crc32(out, n - 4));
	EZ_CHECK_EQ(dev_decrypt(b, -1, out, n, out2, &m), EZ_ERR_NO_SESSION);
	dev_free(a); dev_free(b);
}

/* Integrity: a damaged message is rejected; buffered mode before any key
 * read, streaming at the end -- and in neither case is the RX offset
 * committed (IMPL-ENG-006), so the intact message still decrypts. */
static void t_integrity(void)
{
	ezdev_t *a = dev_new(14), *b = dev_new(15);
	dev_put_key(a, 1, 0x44, 8192, 7);
	dev_copy_key(a, b, 1, 0x44);
	int sa = dev_session(a, 0x44, 1, EZ_ROLE_ALICE, "b");
	int sb = dev_session(b, 0x44, 1, EZ_ROLE_BOB, "a");
	uint32_t n, m;
	EZ_CHECK_EQ(dev_encrypt(a, sa, pt, 1000, out, &n), EZ_OK);
	for (uint32_t pos = 0; pos < n; pos += 37) {
		memcpy(out2, out, n);
		out2[pos] ^= 0x04;
		sim_ks_log_reset(&b->ks, true);
		ez_status_t st = dev_decrypt(b, sb, out2, n, pt, &m);
		EZ_CHECK(st == EZ_ERR_INTEGRITY || st == EZ_ERR_BAD_REQUEST ||
		         st == EZ_ERR_KEY_ID || st == EZ_ERR_RANGE);
		EZ_CHECK_EQ(b->ks.nlog, 0);
		EZ_CHECK(ez_is_zero(b->stage, sizeof b->stage));
		if (pos >= EZ_MSG_HDR) {
			EZ_CHECK_EQ(dev_decrypt_stream(b, sb, out2, n, 100, pt, &m), EZ_ERR_INTEGRITY);
		}
		EZ_CHECK_EQ(b->c.meta.s[sb].rx_off, 0);
	}
	EZ_CHECK_EQ(dev_decrypt(b, sb, out, n, pt, &m), EZ_OK);
	dev_free(a); dev_free(b);
}

/* IMPL-ENG-008/009: resend returns identical bytes with no key access;
 * release and any new staging clear the buffer. */
static void t_resend(void)
{
	ezdev_t *a = dev_new(16);
	dev_put_key(a, 1, 0x66, 8192, 8);
	int s = dev_session(a, 0x66, 1, EZ_ROLE_ALICE, "x");
	uint8_t *p = ez_stage_plaintext(&a->c, 500);
	sim_fill(p, 500, 9);
	const uint8_t *o; uint32_t n, rn;
	EZ_CHECK_EQ(ez_encrypt_buffered(&a->c, s, 500, &o, &n), EZ_OK);
	memcpy(out, o, n);
	uint32_t tx = a->c.meta.s[s].tx_off;
	sim_ks_log_reset(&a->ks, true);
	for (int i = 0; i < 3; i++) {
		const uint8_t *r = ez_retained(&a->c, &rn);
		EZ_CHECK(r != NULL && rn == n && memcmp(r, out, n) == 0);
	}
	EZ_CHECK_MSG(a->ks.nlog == 0, "resend touched key storage");
	EZ_CHECK_EQ(a->c.meta.s[s].tx_off, tx);
	/* New input clears the retained ciphertext. */
	EZ_CHECK(ez_stage_plaintext(&a->c, 10) != NULL);
	EZ_CHECK(ez_retained(&a->c, &rn) == NULL);
	EZ_CHECK(ez_is_zero(a->stage, sizeof a->stage));
	/* Release clears it too. */
	p = ez_stage_plaintext(&a->c, 10);
	memset(p, 'x', 10);
	EZ_CHECK_EQ(ez_encrypt_buffered(&a->c, s, 10, &o, &n), EZ_OK);
	ez_release(&a->c);
	EZ_CHECK(ez_retained(&a->c, &rn) == NULL);
	EZ_CHECK(ez_is_zero(a->stage, sizeof a->stage));
	/* Encrypting needs fresh staging: calling again without it fails and
	 * spends nothing. */
	tx = a->c.meta.s[s].tx_off;
	EZ_CHECK_EQ(ez_encrypt_buffered(&a->c, s, 10, &o, &n), EZ_ERR_BAD_REQUEST);
	EZ_CHECK_EQ(a->c.meta.s[s].tx_off, tx);
	dev_free(a);
}

/* SEC-ENC-003: plaintext is overwritten in place; after a failed
 * encryption nothing of it remains. Decrypted plaintext is cleared on
 * release (SEC-UI-002 at the device). */
static void t_plaintext_cleared(void)
{
	ezdev_t *a = dev_new(17), *b = dev_new(18);
	dev_put_key(a, 1, 0x88, 8192, 10);
	dev_copy_key(a, b, 1, 0x88);
	int sa = dev_session(a, 0x88, 1, EZ_ROLE_ALICE, "b");
	int sb = dev_session(b, 0x88, 1, EZ_ROLE_BOB, "a");
	const uint8_t *o; uint32_t n;
	uint8_t *p = ez_stage_plaintext(&a->c, 64);
	memset(p, 'P', 64);
	EZ_CHECK_EQ(ez_encrypt_buffered(&a->c, sa, 64, &o, &n), EZ_OK);
	uint8_t plain[64];
	memset(plain, 'P', 64);
	EZ_CHECK_MSG(memcmp(o + 16, plain, 64) != 0, "plaintext left in the buffer");
	memcpy(out, o, n);
	uint32_t msg_n = n;
	ez_release(&a->c);
	/* Failure path: capacity exceeded -> buffer wiped, nothing spent. */
	p = ez_stage_plaintext(&a->c, 5000);
	memset(p, 'Q', 5000);
	EZ_CHECK_EQ(ez_encrypt_buffered(&a->c, sa, 5000, &o, &n), EZ_ERR_CAPACITY);
	EZ_CHECK(ez_is_zero(a->stage, sizeof a->stage));
	EZ_CHECK_EQ(a->c.meta.s[sa].tx_off, 64);
	/* Decryption output is cleared on release. */
	EZ_CHECK_EQ(n, 0);                       /* no output length on failure */
	p = ez_stage_message(&b->c, msg_n);
	EZ_CHECK(p != NULL);
	memcpy(p, out, msg_n);
	EZ_CHECK_EQ(ez_decrypt_buffered(&b->c, sb, msg_n, &o, &n), EZ_OK);
	EZ_CHECK(memcmp(o, "PPPP", 4) == 0);
	ez_release(&b->c);
	EZ_CHECK(ez_is_zero(b->stage, sizeof b->stage));
	DEV_KBUF_CLEAR(a); DEV_KBUF_CLEAR(b);
	dev_free(a); dev_free(b);
}

/* Unusable sessions: quarantined, exhausted (decrypt only), empty. */
static void t_session_states(void)
{
	ezdev_t *a = dev_new(19), *b = dev_new(20);
	dev_put_key(a, 1, 0x12, 1024, 11);
	dev_copy_key(a, b, 1, 0x12);
	int sa = dev_session(a, 0x12, 1, EZ_ROLE_ALICE, "b");
	int sb = dev_session(b, 0x12, 1, EZ_ROLE_BOB, "a");
	uint32_t n, m;
	EZ_CHECK_EQ(dev_encrypt(b, sb, pt, 100, out2, &m), EZ_OK);
	EZ_CHECK_EQ(dev_encrypt(a, sa, pt, 512, out, &n), EZ_OK);       /* exhausts TX */
	EZ_CHECK_EQ(a->c.meta.s[sa].state, EZ_SS_EXHAUSTED);
	EZ_CHECK_EQ(dev_encrypt(a, sa, pt, 1, out, &n), EZ_ERR_CAPACITY);
	EZ_CHECK_EQ(dev_decrypt(a, sa, out2, m, pt, &n), EZ_OK);       /* still decrypts */
	EZ_CHECK_EQ(ez_meta_quarantine(&b->c.meta, sb, EZ_Q_KEY_MISSING), EZ_OK);
	EZ_CHECK_EQ(dev_encrypt(b, sb, pt, 1, out, &n), EZ_ERR_QUARANTINED);
	EZ_CHECK_EQ(dev_encrypt_stream(b, sb, pt, 1, 1, out, &n), EZ_ERR_QUARANTINED);
	EZ_CHECK_EQ(dev_encrypt(b, 7, pt, 1, out, &n), EZ_ERR_NO_SESSION);
	EZ_CHECK_EQ(dev_encrypt(b, 99, pt, 1, out, &n), EZ_ERR_BAD_REQUEST);
	dev_free(a); dev_free(b);
}

/* One stream at a time; buffered staging refused while streaming. */
static void t_stream_exclusive(void)
{
	ezdev_t *a = dev_new(21);
	dev_put_key(a, 1, 0x31, 8192, 12);
	int s = dev_session(a, 0x31, 1, EZ_ROLE_ALICE, "x");
	ez_stream_t s1, s2;
	uint8_t hdr[16];
	EZ_CHECK_EQ(ez_enc_stream_begin(&a->c, &s1, s, 100, hdr), EZ_OK);
	EZ_CHECK_EQ(ez_enc_stream_begin(&a->c, &s2, s, 100, hdr), EZ_ERR_BUSY);
	EZ_CHECK(ez_stage_plaintext(&a->c, 10) == NULL);
	uint8_t buf[60] = {0};
	EZ_CHECK_EQ(ez_enc_stream_update(&a->c, &s1, buf, 60), EZ_OK);
	EZ_CHECK_EQ(ez_stream_spent(&s1), 60);
	EZ_CHECK_EQ(ez_enc_stream_update(&a->c, &s1, buf, 41), EZ_ERR_BAD_REQUEST); /* overrun */
	EZ_CHECK(!a->c.stream_active);
	EZ_CHECK_EQ(a->c.meta.s[s].tx_off, 60);   /* spent exactly what was output */
	dev_free(a);
}

/* SEC-STORE-004 / IMPL-ENG-013: damaged key data (here a 16-byte patch of
 * 0x00 or 0xFF in unit 1, not reflected in the .SUM) is refused before any
 * of its unit's bytes are used: no output, no commit. The session is not
 * quarantined; IMPL-ENG-014 skip moves the TX offset past the damage. */
static void damaged(uint8_t fill, int stream)
{
	ezdev_t *d = dev_new(22);
	dev_put_key(d, 1, 0xDA, 32768, 13);                 /* alice TX: units 0..3 */
	sim_file_t *f = sim_ks_get(&d->ks, 1, "000000DA.KEY");
	memset(f->data + 5000, fill, 16);                   /* unit 1 */
	int s = dev_session(d, 0xDA, 1, EZ_ROLE_ALICE, "x");
	uint32_t n;
	EZ_CHECK_EQ(dev_encrypt(d, s, pt, 4090, out, &n), EZ_OK);   /* unit 0: fine */
	ez_status_t st = stream ? dev_encrypt_stream(d, s, pt, 100, 7, out, &n)
	                        : dev_encrypt(d, s, pt, 100, out, &n);
	EZ_CHECK_EQ(st, EZ_ERR_KEY_DAMAGED);
	EZ_CHECK(d->c.damage.valid && d->c.damage.unit == 1);
	/* Streaming: the first chunk already reaches into unit 1 (4090+7 >
	 * 4096), so nothing at all was output or committed. */
	EZ_CHECK_EQ(d->c.meta.s[s].tx_off, 4090);
	EZ_CHECK(ez_is_zero(d->stage, sizeof d->stage));
	EZ_CHECK_EQ(d->c.meta.s[s].state, EZ_SS_VALID);       /* not quarantined */
	DEV_KBUF_CLEAR(d);
	/* Skip: forward to the start of unit 2, logged without the offset. */
	uint32_t units;
	EZ_CHECK_EQ(ez_session_skip(&d->c, s, &units), EZ_OK);
	EZ_CHECK_EQ(units, 1);
	EZ_CHECK_EQ(d->c.meta.s[s].tx_off, 8192);
	EZ_CHECK_EQ(ez_session_skip(&d->c, s, &units), EZ_ERR_STATE);   /* nothing to skip */
	ez_event_t ev[1];
	EZ_CHECK_EQ(ez_meta_log_read(&d->c.meta, ev, 1), 1);
	EZ_CHECK_EQ(ev[0].type, EZ_EV_SKIP);
	EZ_CHECK_EQ(ev[0].arg, 0);
	EZ_CHECK_EQ(dev_encrypt(d, s, pt, 100, out, &n), EZ_OK);
	EZ_CHECK_EQ(ez_get_le32(out + 8), 8192);
	DEV_KBUF_CLEAR(d);
	dev_free(d);
}
static void t_damaged_zero(void)        { damaged(0x00, 0); }
static void t_damaged_ff_stream(void)   { damaged(0xFF, 1); }

/* Damage on the receiving side: the message covering it is refused, the
 * RX offset is not advanced, and nothing is released. */
static void t_damaged_rx(void)
{
	ezdev_t *a = dev_new(23), *b = dev_new(24);
	dev_put_key(a, 1, 0xDB, 8192, 14);
	dev_copy_key(a, b, 1, 0xDB);
	int sa = dev_session(a, 0xDB, 1, EZ_ROLE_ALICE, "b");
	sim_file_t *f = sim_ks_get(&b->ks, 1, "000000DB.KEY");
	f->data[10] ^= 0x01;                                /* a single bit in bob's RX range */
	int sb = dev_session(b, 0xDB, 1, EZ_ROLE_BOB, "a");
	uint32_t n, m;
	EZ_CHECK_EQ(dev_encrypt(a, sa, pt, 100, out, &n), EZ_OK);
	EZ_CHECK_EQ(dev_decrypt(b, sb, out, n, out2, &m), EZ_ERR_KEY_DAMAGED);
	EZ_CHECK_EQ(dev_decrypt_stream(b, sb, out, n, 10, out2, &m), EZ_ERR_KEY_DAMAGED);
	EZ_CHECK_EQ(m, 0);
	EZ_CHECK_EQ(b->c.meta.s[sb].rx_off, 0);
	EZ_CHECK(ez_is_zero(b->stage, sizeof b->stage));
	DEV_KBUF_CLEAR(b);
	dev_free(a); dev_free(b);
}

/* Damage in the integrity file itself is equally refused. */
static void t_damaged_tag(void)
{
	ezdev_t *d = dev_new(25);
	dev_put_key(d, 1, 0xDC, 16384, 15);
	sim_file_t *f = sim_ks_get(&d->ks, 1, "000000DC.SUM");
	f->data[EZ_SUM_HDR + 3] ^= 0x80;                     /* tag of unit 0 */
	int s = dev_session(d, 0xDC, 1, EZ_ROLE_ALICE, "x");
	uint32_t n;
	EZ_CHECK_EQ(dev_encrypt(d, s, pt, 10, out, &n), EZ_ERR_KEY_DAMAGED);
	EZ_CHECK_EQ(d->c.meta.s[s].tx_off, 0);
	f->data[EZ_SUM_HDR + 3] ^= 0x80;
	f->data[5] ^= 0x01;                                  /* header */
	EZ_CHECK_EQ(dev_encrypt(d, s, pt, 10, out, &n), EZ_ERR_KEY_DAMAGED);
	dev_free(d);
}

/* IMPL-KEY-005: another card carrying a different key under the same Key
 * ID, with a perfectly valid integrity file of its own, is refused. */
static void t_other_key_same_id(void)
{
	ezdev_t *d = dev_new(26);
	dev_put_key(d, 1, 0xDD, 16384, 16);
	int s = dev_session(d, 0xDD, 1, EZ_ROLE_ALICE, "x");
	uint32_t n;
	EZ_CHECK_EQ(dev_encrypt(d, s, pt, 10, out, &n), EZ_OK);
	dev_put_key(d, 1, 0xDD, 16384, 99);                  /* the other card */
	sim_ks_insert(&d->ks, 1);
	EZ_CHECK_EQ(dev_encrypt(d, s, pt, 10, out, &n), EZ_ERR_KEY_DAMAGED);
	EZ_CHECK(d->c.damage.unit == UINT32_MAX);
	EZ_CHECK_EQ(d->c.meta.s[s].tx_off, 10);
	/* The original card back: works again. */
	dev_put_key(d, 1, 0xDD, 16384, 16);
	EZ_CHECK_EQ(dev_encrypt(d, s, pt, 10, out, &n), EZ_OK);
	dev_free(d);
}

/* A key without its integrity file cannot start a session directly
 * (SEC-STORE-004): it must be imported. An existing session whose .SUM
 * disappears is quarantined. */
static void t_no_sum(void)
{
	ezdev_t *d = dev_new(27);
	uint8_t k[16384];
	sim_fill(k, sizeof k, 5);
	sim_ks_put(&d->ks, 1, "000000DE.KEY", k, sizeof k);
	int s;
	EZ_CHECK_EQ(ez_session_create(&d->c, 0xDE, 1, EZ_ROLE_ALICE, "x", &s), EZ_ERR_UNVERIFIED);
	dev_put_key(d, 1, 0xDF, 16384, 6);
	s = dev_session(d, 0xDF, 1, EZ_ROLE_ALICE, "y");
	EZ_CHECK_EQ(d->ks.hal.zap(d->ks.hal.ctx, 1, "000000DF.SUM"), EZ_OK);
	uint32_t n;
	EZ_CHECK_EQ(dev_encrypt(d, s, pt, 10, out, &n), EZ_ERR_QUARANTINED);
	EZ_CHECK_EQ(d->c.meta.s[s].qreason, EZ_Q_KEY_MISSING);
	dev_free(d);
}

